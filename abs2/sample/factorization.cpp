/// @brief Converts a number to a binary string.
/// @param num The number to be easyerted.
/// @return std::string The binary string.
std::string toBinaryString(uint64_t num) {
  if (num == 0) return "0";
  std::string binary = "";
  while (num > 0) {
    binary = (num % 2 == 0 ? "0" : "1") + binary;
    num /= 2;
  }
  return binary;
}

/// @brief Converts a vector of Var in a solution to a 64-bit unsigned integer.
/// @param sol The solution.
/// @param var The vector of Var.
/// @param fix_lsb True if the LSBs of x, y, and z are fixed to 1.
/// @return uint64_t The 64-bit unsigned integer.
uint64_t as_uint64(const qbpp::Sol &sol, const qbpp::Vector<qbpp::Var> &var,
                   bool fix_lsb) {
  uint64_t result = 0;
  for (int i = var.size() - 1; i >= 1; --i) {
    result = (result << 1) + sol.get(var[i]);
  }
  if (fix_lsb) {
    result = (result << 1) + 1;
  } else {
    result = (result << 1) + sol.get(var[0]);
  }
  return result;
}

/// @brief Converts a vector of Var in a solution holder to a 64-bit unsigned
/// integer.
/// @param sol_holder The solution holder.
/// @param var The vector of Var.
/// @param fix_lsb True if the LSBs of x, y, and z are fixed to 1.
/// @return uint64_t The 64-bit unsigned integer.
uint64_t as_uint64(const qbpp::SolHolder &sol_holder,
                   const qbpp::Vector<qbpp::Var> &var, bool fix_lsb) {
  return as_uint64(sol_holder.copy_sol(), var, fix_lsb);
}

bool is_prime(uint32_t num) {
  return boost::multiprecision::miller_rabin_test(
      boost::multiprecision::uint128_t(num), 25);
}

/// @brief Generates a random prime number of the specified size.
/// @param size The number of bits of the prime number.
/// @return uint32_t Random prime number. The MSB is 1.
/// @note The prime number is generated by the Miller-Rabin primality test.
uint32_t rand_prime(int size) {
  uint32_t num;
  do {
    num = qbpp::misc::RandomGenerator::gen(1 << (size - 2)) |
          (1 << (size - 1)) | 1;
  } while (is_prime(num) == false);
  return num;
}

/// @brief Solution holder to store the best solution of factorization.
/// @note Inherited from qbpp::SolHolder. Member variable "bound", which stores
/// the bound of the best solution found by Gurobi, is added.

class SolHolder : public qbpp::SolHolder {
  /// @brief True if factorization, false if multiplication.
  const bool factorization_mode = true;
  ///@brief True if the MSBs and LSBs of x, y, and z are fixed.
  const bool fix_lsb = false;
  /// @brief The vector of Var.
  const qbpp::Vector<qbpp::Var> &var_x;
  /// @brief The vector of Var.
  const qbpp::Vector<qbpp::Var> &var_y;
  /// @brief The vector of Var.
  const qbpp::Vector<qbpp::Var> &var_z;
  /// @brief The bound of the best solution found by Gurobi.
  std::optional<int64_t> bound = std::nullopt;
  /// @brief Mutex for thread safety in print function.
  mutable std::mutex mtx;

 public:
  /// @brief Constructor with a quad_model.
  /// @param quad_model The QUBO quad_model.
  /// @param fix_lsb True if the LSBs of x and y are fixed to 1.
  /// @param var_x The vector of Var.
  /// @param var_y The vector of Var.
  SolHolder(const qbpp::QuadModel &quad_model, bool fix_lsb,
            const qbpp::Vector<qbpp::Var> &var_x,
            const qbpp::Vector<qbpp::Var> &var_y)
      : qbpp::SolHolder(quad_model),
        fix_lsb(fix_lsb),
        var_x(var_x),
        var_y(var_y),
        var_z(std::move(qbpp::Vector<qbpp::Var>{})) {}

  /// @brief Constructor with a quad_model.
  /// @param quad_model The QUBO quad_model.
  /// @param fix_lsb True if the LSBs of z are fixed to 1.
  /// @param var_z The vector of Var.
  SolHolder(const qbpp::QuadModel &quad_model, bool fix_lsb,
            const qbpp::Vector<qbpp::Var> &var_z)
      : qbpp::SolHolder(quad_model),
        factorization_mode(false),
        fix_lsb(fix_lsb),
        var_x(std::move(qbpp::Vector<qbpp::Var>{})),
        var_y(std::move(qbpp::Vector<qbpp::Var>{})),
        var_z(var_z) {}

  SolHolder(const SolHolder &sol_holder) = default;

  /// @brief Sets the bound value of the best solution.
  /// @param bound The bound value.
  void set_bound(int64_t bound) { this->bound = bound; }

  /// @brief Gets the bound value of the best solution.
  /// @return int64_t The bound value.
  std::optional<int64_t> get_bound() const { return bound; }

  /// @brief Gets the bound value of the best solution as a string.
  /// @return std::string The bound value as a string.
  std::string get_bound_str() const {
    if (bound.has_value()) {
      return std::to_string(bound.value());
    } else {
      return "N/A";
    }
  }

  /// @brief Sets new_sol as the best solution if it is better than the current
  /// best solution.
  /// @param new_sol The new solution.
  /// @param solver The solver name.
  /// @return std::optional<std::chrono::milliseconds> The time to solution if
  /// the current best solution is updated by new_sol.
  std::optional<double> set_if_better(const qbpp::Sol &new_sol,
                                      const std::string &solver) override {
    std::lock_guard<std::mutex> lock(mtx);
    std::optional<double> tts = qbpp::SolHolder::set_if_better(new_sol, solver);
    if (tts.has_value()) {
      std::cerr << std::left << std::setw(4) << get_solver() << " "
                << std::fixed << std::setprecision(3) << tts.value()
                << "s Energy = " << new_sol.energy()
                << " Bound = " << get_bound_str() << " : ";
      if (factorization_mode) {
        std::cerr << toBinaryString(as_uint64(new_sol, var_x, fix_lsb)) << " * "
                  << toBinaryString(as_uint64(new_sol, var_y, fix_lsb)) << " = "
                  << toBinaryString(as_uint64(new_sol, var_x, fix_lsb) *
                                    as_uint64(new_sol, var_y, fix_lsb))
                  << " (" << as_uint64(new_sol, var_x, fix_lsb) << " * "
                  << as_uint64(new_sol, var_y, fix_lsb) << " = "
                  << as_uint64(new_sol, var_x, fix_lsb) *
                         as_uint64(new_sol, var_y, fix_lsb)
                  << ")" << std::endl;
      } else {
        std::cout << toBinaryString(as_uint64(new_sol, var_z, fix_lsb)) << " ("
                  << as_uint64(new_sol, var_z, fix_lsb) << ")" << std::endl;
      }
    }
    return tts;
  }
};

/// @brief Class to define ABS2 callback function for factorization.
class ABS2Callback : public qbpp_abs2::Callback {
  /// @brief The solution holder.
  //  SolHolder &sol_holder;
  const std::shared_ptr<SolHolder> sol_holder_ptr_;

 public:
  /// @brief Construct a new ABS2Callback object for factorization.
  /// @param quad_model The ABS2 quad_model.
  /// @param sol_holder_ptr The pointer to the solution holder given to the
  /// ABS2Callback.
  ABS2Callback(const qbpp_abs2::QuadModel &quad_model,
               std::shared_ptr<SolHolder> sol_holder_ptr)
      : qbpp_abs2::Callback(quad_model), sol_holder_ptr_(sol_holder_ptr) {}

  void callback(const std::string &event) override {
    if (event == "init") {
      // Enable the callback for every new best solution.
      qbpp_abs2::Callback::set("new");
    } else {
      auto sol = get_sol();
      if (event == "new") {
        sol_holder_ptr_->set_if_better(sol, "ABS2");
      }
      auto hint = sol_holder_ptr_->get_if_better(sol);
      if (hint.has_value()) set_hint(hint.value());
    }
    qbpp_abs2::Callback::set("alarm", "1");
  }
};  // namespace factorization

/// @brief Class to define Gurobi callback function for factorization.
/// @note This Gurobi callback inherits from qbpp_grb::Callback.
class GRB_Callback : public qbpp_grb::Callback {
  /// @brief The solution holder for Gurobi.
  //  SolHolder &sol_holder;
  std::shared_ptr<SolHolder> sol_holder_ptr_;
  /// @brief Target energy to stop the Gurobi optimizer.
  /// std::optional<qbpp::energy_t> target_energy = std::nullopt;

 public:
  /// @brief Construct a new grb callback object
  /// @param quad_model The Gurobi quad_model.
  /// @param sol_holder_ptr The pinter to the solution holder given to the
  /// Gurobi Optimizer.
  GRB_Callback(qbpp_grb::QuadModel &quad_model,
               std::shared_ptr<SolHolder> sol_holder_ptr)
      : qbpp_grb::Callback(quad_model), sol_holder_ptr_(sol_holder_ptr) {}

  /// @brief callback function for Gurobi optimizer.
  /// @details The callback function is called by the Gurobi optimizer for
  /// every event.
  void callback() override {
    if (where == GRB_CB_MIPSOL) {
      qbpp_grb::Sol sol = get_sol();
      sol_holder_ptr_->set_if_better(sol, "GRB");
    }
    if (where == GRB_CB_MIP) {
      sol_holder_ptr_->set_bound(
          std::round(getDoubleInfoPublic(GRB_CB_MIP_OBJBND)));
      auto hint = sol_holder_ptr_->get_if_better(
          std::round(getDoubleInfoPublic(GRB_CB_MIP_OBJBST)));
      if (hint.has_value()) {
        for (qbpp::vindex_t i = 0; i < quad_model.var_count(); ++i) {
          setSolution(quad_model.get_grb_var(i), hint.value().get(i));
        }
        useSolution();
      }
    }
    if (where == GRB_CB_MIPNODE) {
      sol_holder_ptr_->set_bound(
          std::round(getDoubleInfoPublic(GRB_CB_MIPNODE_OBJBND)));
      auto hint = sol_holder_ptr_->get_if_better(
          std::round(getDoubleInfoPublic(GRB_CB_MIPNODE_OBJBST)));
      if (hint.has_value()) {
        for (qbpp::vindex_t i = 0; i < quad_model.var_count(); ++i) {
          setSolution(quad_model.get_grb_var(i), hint.value().get(i));
        }
        useSolution();
      }
    }
    abort_if_target_energy(sol_holder_ptr_->energy());
  }
};

