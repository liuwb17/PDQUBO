/// @file factorization.cpp
/// @author Koji Nakano
/// @brief Solves factorization and multiplication problems for two prime
/// numbers using multiple QUBO solvers.
/// @details This program generates a QUBO model for
/// factorization/multiplication using QUBO++ and solves it simultaneously
/// using various QUBO solvers. Factorization/multiplication QUBO models are
/// designed to simulate a binary multiplier. It supports the ABS2 GPU QUBO
/// solver, the Gurobi optimizer, and the QUBO++ Easy solver. When a better
/// solution is found by a solver, the other solvers are notified via callback
/// functions for further improvement. The QUBO models are designed to
/// simulate a binary multiplier.
/// @note While it is impractical to perform factorization/multiplication
/// through QUBO models due to their complexity, these problems are useful
/// for understanding the usage of the QUBO++ library and for demonstrating the
/// capabilities of QUBO solvers.
/// @version 2024-10-04

